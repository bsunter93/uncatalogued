const f = n => Math.round(n * 10) / 10;
const D = Math.PI / 180;
const pol = (x, y, r, a) => [x + r * Math.cos(a * D), y + r * Math.sin(a * D)];

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function hash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

// ---- primitives. k: 'i' ink fill, 'j' dim fill, 's' ink stroke, 't' dim stroke
const E = (cx, cy, rx, ry, o, k = 'i', rot = 0) =>
  `<ellipse cx="${f(cx)}" cy="${f(cy)}" rx="${f(rx)}" ry="${f(ry)}" class="${k}" opacity="${o}"${rot ? ` transform="rotate(${f(rot)} ${f(cx)} ${f(cy)})"` : ''}/>`;
const C = (cx, cy, r, o, k = 'i') => `<circle cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}" class="${k}" opacity="${o}"/>`;
const P = (d, o, k = 'i') => `<path d="${d}" class="${k}" opacity="${o}"/>`;
const PE = (d, o, k = 'i') => `<path d="${d}" class="${k}" opacity="${o}" fill-rule="evenodd"/>`;
const S = (d, w, o, k = 's') => `<path d="${d}" class="${k}" stroke-width="${w}" opacity="${o}"/>`;
const pts = a => 'M' + a.map(p => f(p[0]) + ' ' + f(p[1])).join('L');
const PG = (a, o, k = 'i') => P(pts(a) + 'Z', o, k);
const L = (a, w, o, k = 's') => S(pts(a), w, o, k);
const ML = (segs, w, o, k = 's') => S(segs.map(pts).join(''), w, o, k);
const hole = (cx, cy, rx, ry = rx) =>
  `M${f(cx + rx)} ${f(cy)}A${f(rx)} ${f(ry)} 0 1 0 ${f(cx - rx)} ${f(cy)}A${f(rx)} ${f(ry)} 0 1 0 ${f(cx + rx)} ${f(cy)}Z`;
function ring(cx, cy, r, w, o, k = 's', gap = 0, rot = 0) {
  const c = 2 * Math.PI * r;
  return `<circle cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}" class="${k}" stroke-width="${w}" opacity="${o}"` +
    (gap ? ` stroke-dasharray="${f(c * (1 - gap))} ${f(c * gap)}" transform="rotate(${f(rot)} ${f(cx)} ${f(cy)})"` : '') + '/>';
}
function arc(cx, cy, r, a0, a1, w, o, k = 's') {
  const p = pol(cx, cy, r, a0), q = pol(cx, cy, r, a1);
  return S(`M${f(p[0])} ${f(p[1])}A${f(r)} ${f(r)} 0 ${a1 - a0 > 180 ? 1 : 0} 1 ${f(q[0])} ${f(q[1])}`, w, o, k);
}
function leaf(x, y, len, w, a, o, k = 'i', vein = 1) {
  const t = pol(x, y, len, a), m = pol(x, y, len * .45, a), c1 = pol(m[0], m[1], w, a + 90), c2 = pol(m[0], m[1], w, a - 90);
  return P(`M${f(x)} ${f(y)}Q${f(c1[0])} ${f(c1[1])} ${f(t[0])} ${f(t[1])}Q${f(c2[0])} ${f(c2[1])} ${f(x)} ${f(y)}Z`, o, k) +
    (vein ? L([[x, y], t], .4, Math.min(1, o + .3)) : '');
}
function frond(x, y, len, a, n, o, k = 'i', sp = 55) {
  let s = L([[x, y], pol(x, y, len, a)], .6, Math.min(1, o + .25));
  for (let i = 1; i <= n; i++) {
    const t = i / (n + 1), p = pol(x, y, len * t, a), l = len * .42 * (1 - t * .6);
    s += leaf(p[0], p[1], l, l * .28, a - sp, o, k, 0) + leaf(p[0], p[1], l, l * .28, a + sp, o, k, 0);
  }
  const e = pol(x, y, len * .8, a);
  return s + leaf(e[0], e[1], len * .3, len * .08, a, o, k, 0);
}
const spike = (x, y, len, w, a, o, k = 'i') => PG([pol(x, y, w, a + 90), pol(x, y, len, a), pol(x, y, w, a - 90)], o, k);
function burst(cx, cy, r0, len, n, a0, a1, w, o, k = 'i') {
  let s = '';
  for (let i = 0; i < n; i++) {
    const a = a0 + (a1 - a0) * i / Math.max(1, n - 1), b = pol(cx, cy, r0, a);
    s += spike(b[0], b[1], len * (i % 2 ? .72 : 1), w, a, o, k);
  }
  return s;
}
function gear(cx, cy, r, n, o, k = 'i', hl = .38, depth = .22) {
  let d = '';
  const ri = r * (1 - depth), w = 360 / n;
  for (let i = 0; i < n; i++) {
    const a = i * w;
    d += (i ? 'L' : 'M') + [pol(cx, cy, ri, a), pol(cx, cy, r, a + w * .14), pol(cx, cy, r, a + w * .42), pol(cx, cy, ri, a + w * .56)]
      .map(q => f(q[0]) + ' ' + f(q[1])).join('L');
  }
  d += 'Z' + (hl ? hole(cx, cy, r * hl) : '');
  return PE(d, o, k);
}
function coil(a, b, turns, amp, w, o, k = 's') {
  const n = turns * 2, dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy) || 1, nx = -dy / l, ny = dx / l, p = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n, m = i === 0 || i === n ? 0 : (i % 2 ? amp : -amp);
    p.push([a[0] + dx * t + nx * m, a[1] + dy * t + ny * m]);
  }
  return L(p, w, o, k);
}
function spiral(cx, cy, r0, r1, turns, a0, w, o, k = 's') {
  const p = [], n = Math.ceil(turns * 18);
  for (let i = 0; i <= n; i++) { const t = i / n; p.push(pol(cx, cy, r0 + (r1 - r0) * t, a0 + t * turns * 360)); }
  return L(p, w, o, k);
}
